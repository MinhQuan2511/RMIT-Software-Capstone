/**
 * Regenerates test/fixtures.mjs from the real backend pipeline, so frontend
 * tests consume canonical revision data rather than hand-written coordinates.
 *   node test/make-fixtures.cjs
 */
const fs = require('fs');
const path = require('path');
const { runPipeline } = require('../../backend/services/jobs/jobService');
const { sha256 } = require('../../backend/services/util/hash');

function record(label, content, parameters = {}) {
  const meta = { id: 'src_demo_000000000000000000000000', sha256: sha256(content), contentType: 'feature-text', sourceKind: 'demo', displayName: label };
  const r = runPipeline(meta, content, parameters);
  if (!r.ok) throw new Error(`${label}: ${JSON.stringify(r.diagnostics)}`);
  return {
    mode: 'file_import',
    source: { id: meta.id, sha256: meta.sha256, kind: 'demo', displayName: label },
    parameters: r.resolved.parameters,
    profile: { id: r.profile.id, version: r.profile.version },
    geometry: r.plan.geometry,
    orientation: r.plan.orientation || null,
    path: { waypoints: r.plan.waypoints, segments: r.plan.segments, targetCount: r.plan.waypoints.length, instructionCount: r.plan.segments.length },
    output: { sha256: r.compiled.outputSha256 },
  };
}

const sample = (file) => fs.readFileSync(path.join(__dirname, '../../samples', file));

// SYNTHETIC fixture: a straight seam along +X with a declared wall-left fillet and a synthetic tool convention.
const JOINT_SOURCE = Buffer.from('units: mm\n# SYNTHETIC FIXTURE (not a measurement)\ncurve: 400, 100, 300, 600, 100, 300, 5\n');
const JOINT_PARAMETERS = {
  profileId: 'joint-relative-fillet',
  station: { id: 'synthetic-tool-z-approach' },
  joint: { kind: 'template', template: 'fillet90_wall_left', referenceNormal: [0, 0, 1] },
  orientation: { workAngleDeg: 45, pushAngleDeg: 10 },
};

const out = `// Generated by test/make-fixtures.cjs from the backend pipeline. Do not edit by hand.\n` +
  `export const STRAIGHT_RECORD = ${JSON.stringify(record('Feature_Straight_Sample.txt', sample('Feature_Straight_Sample.txt')), null, 2)};\n\n` +
  `export const ARC_RECORD = ${JSON.stringify(record('Feature_Arc_Sample.txt', sample('Feature_Arc_Sample.txt')), null, 2)};\n\n` +
  `// SYNTHETIC joint-relative fixture (synthetic seam + synthetic station profile).\n` +
  `export const JOINT_RECORD = ${JSON.stringify(record('synthetic_fillet_fixture.txt', JOINT_SOURCE, JOINT_PARAMETERS), null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, 'fixtures.mjs'), out);
console.log('wrote test/fixtures.mjs');
