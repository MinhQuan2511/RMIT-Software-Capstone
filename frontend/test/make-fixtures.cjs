/**
 * Regenerates test/fixtures.mjs from the real backend pipeline, so frontend
 * tests consume canonical revision data rather than hand-written coordinates.
 *   node test/make-fixtures.cjs
 */
const fs = require('fs');
const path = require('path');
const { runPipeline } = require('../../backend/services/jobs/jobService');
const { sha256 } = require('../../backend/services/util/hash');

function record(file) {
  const content = fs.readFileSync(path.join(__dirname, '../../samples', file));
  const meta = { id: 'src_demo_000000000000000000000000', sha256: sha256(content), contentType: 'feature-text', sourceKind: 'demo', displayName: file };
  const r = runPipeline(meta, content, {});
  if (!r.ok) throw new Error(`${file}: ${JSON.stringify(r.diagnostics)}`);
  return {
    mode: 'file_import',
    source: { id: meta.id, sha256: meta.sha256, kind: 'demo', displayName: file },
    geometry: r.plan.geometry,
    path: { waypoints: r.plan.waypoints, segments: r.plan.segments, targetCount: r.plan.waypoints.length, instructionCount: r.plan.segments.length },
    output: { sha256: r.compiled.outputSha256 },
  };
}

const out = `// Generated by test/make-fixtures.cjs from the backend pipeline. Do not edit by hand.\n` +
  `export const STRAIGHT_RECORD = ${JSON.stringify(record('Feature_Straight_Sample.txt'), null, 2)};\n\n` +
  `export const ARC_RECORD = ${JSON.stringify(record('Feature_Arc_Sample.txt'), null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, 'fixtures.mjs'), out);
console.log('wrote test/fixtures.mjs');
