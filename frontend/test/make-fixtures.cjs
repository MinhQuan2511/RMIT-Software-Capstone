/**
 * Regenerates test/fixtures.mjs from the real backend pipeline, so frontend
 * tests consume canonical revision data rather than hand-written coordinates.
 *   node test/make-fixtures.cjs
 * Every geometry fixture here is SYNTHETIC.
 */
const fs = require('fs');
const path = require('path');
const { runPipeline } = require('../../backend/services/jobs/jobService');
const { sha256 } = require('../../backend/services/util/hash');
const { filletOnSeam } = require('../../backend/test/geometryFixtures');
const { SYNTHETIC_Z_APPROACH } = require('../../backend/services/geometry/toolEnvelope');

function record(label, content, parameters = {}) {
  const meta = { id: 'src_demo_000000000000000000000000', sha256: sha256(content), contentType: 'feature-text', sourceKind: 'demo', displayName: label };
  const r = runPipeline(meta, content, parameters);
  if (!r.ok) throw new Error(`${label}: ${JSON.stringify(r.diagnostics)}`);
  return {
    jobId: `job_fixture_${label.replace(/[^a-z0-9]/gi, '_')}`,
    revision: 1,
    mode: 'file_import',
    source: { id: meta.id, sha256: meta.sha256, kind: 'demo', displayName: label },
    parameters: r.resolved.parameters,
    profile: { id: r.profile.id, version: r.profile.version },
    geometry: r.plan.geometry,
    orientation: r.plan.orientation || null,
    workpiece: r.workpiece,
    toolEnvelope: { definition: r.toolEnvelope },
    clearance: r.clearance,
    diagnostics: r.diagnostics,
    path: { waypoints: r.plan.waypoints, segments: r.plan.segments, targetCount: r.plan.waypoints.length, instructionCount: r.plan.segments.length },
    output: { sha256: r.compiled.outputSha256 },
    configurationSha256: r.configurationSha256,
  };
}

const sample = (file) => fs.readFileSync(path.join(__dirname, '../../samples', file));

// SYNTHETIC fixture: a straight seam along +X with a declared wall-left fillet and a synthetic tool convention.
const JOINT_SOURCE = Buffer.from('units: mm\n# SYNTHETIC FIXTURE (not a measurement)\ncurve: 400, 100, 300, 600, 100, 300, 5\n');
const SEAM = { start: [400, 100, 300], end: [600, 100, 300] };
const JOINT_PARAMETERS = {
  profileId: 'joint-relative-fillet',
  station: { id: 'synthetic-tool-z-approach' },
  joint: { kind: 'template', template: 'fillet90_wall_left', referenceNormal: [0, 0, 1] },
  orientation: { workAngleDeg: 45, pushAngleDeg: 10 },
};
const FROM_WORKPIECE = (workpiece, extra = {}) => ({ ...JOINT_PARAMETERS, joint: { kind: 'workpiece' }, workpiece, toolEnvelope: SYNTHETIC_Z_APPROACH, ...extra });

// SYNTHETIC rotated and sloped seam: azimuth 120°, slope 20°, 180 mm.
const RAD = Math.PI / 180;
const ROT_START = [300, -50, 250];
const ROT_END = [0, 1, 2].map((i) => Number((ROT_START[i] + 180 * [Math.cos(20 * RAD) * Math.cos(120 * RAD), Math.cos(20 * RAD) * Math.sin(120 * RAD), Math.sin(20 * RAD)][i]).toFixed(4)));
const ROT_SOURCE = Buffer.from(`units: mm\n# SYNTHETIC rotated and sloped fixture\ncurve: ${ROT_START.join(', ')}, ${ROT_END.join(', ')}, 5\n`);
const LEGACY_SEAM = { start: [414.69, 1112.75, 320.342], end: [338.531, 1333.74, 322.068] };

const fixtures = {
  STRAIGHT_RECORD: ['Legacy straight sample, no workpiece (seam-only mode)', record('Feature_Straight_Sample.txt', sample('Feature_Straight_Sample.txt'))],
  ARC_RECORD: ['Legacy arc sample', record('Feature_Arc_Sample.txt', sample('Feature_Arc_Sample.txt'))],
  JOINT_RECORD: ['SYNTHETIC joint-relative fixture (synthetic seam + synthetic station profile), no workpiece', record('synthetic_fillet_fixture.txt', JOINT_SOURCE, JOINT_PARAMETERS)],
  TEE_RECORD: ['SYNTHETIC operator-defined tee, wall left, joint from workpiece, synthetic envelope', record('synthetic_tee.txt', JOINT_SOURCE, FROM_WORKPIECE(filletOnSeam(SEAM)))],
  CORNER_REVERSED_RECORD: ['SYNTHETIC illustrative corner, wall right, reversed traversal', record('synthetic_corner.txt', JOINT_SOURCE, FROM_WORKPIECE(filletOnSeam({ ...SEAM, side: 'right', arrangement: 'corner', provenance: 'illustrative' }), { traversal: 'reversed' }))],
  ROTATED_RECORD: ['SYNTHETIC rotated (120°) and sloped (20°) corner', record('synthetic_rotated.txt', ROT_SOURCE, FROM_WORKPIECE(filletOnSeam({ start: ROT_START, end: ROT_END, arrangement: 'corner' })))],
  INTERSECT_RECORD: ['Legacy straight sample with an operator-defined wall on the LEFT: approach/retract cross it', record('Feature_Straight_Sample.txt', sample('Feature_Straight_Sample.txt'), { workpiece: filletOnSeam({ ...LEGACY_SEAM, side: 'left' }) })],
};

const out = `// Generated by test/make-fixtures.cjs from the backend pipeline. Do not edit by hand.\n` +
  Object.entries(fixtures).map(([name, [comment, rec]]) => `// ${comment}\nexport const ${name} = ${JSON.stringify(rec, null, 2)};\n`).join('\n');
fs.writeFileSync(path.join(__dirname, 'fixtures.mjs'), out);
console.log(`wrote test/fixtures.mjs (${Object.keys(fixtures).join(', ')})`);
